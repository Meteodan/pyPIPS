"""Regression test: the refactored DSDlib.calc_evap wrapper must reproduce the original output.

The reference file was generated by data/make_calc_evap_reference.py against the original
(pre-refactor) implementation of calc_evap.
"""
from __future__ import annotations

import os

import numpy as np

import pyPIPS.DSDlib as dsd

REFERENCE_FILE = os.path.join(os.path.dirname(__file__), 'data', 'calc_evap_reference.npz')


def test_calc_evap_matches_original_reference():
    ref = np.load(REFERENCE_FILE)
    QREVP, COOL_RATE = dsd.calc_evap(ref['rho'], ref['T'], ref['p'], ref['RH'], ref['N0'],
                                     ref['lamda'], ref['mu'])
    np.testing.assert_allclose(QREVP, ref['QREVP'], rtol=1.e-10, atol=0.)
    np.testing.assert_allclose(COOL_RATE, ref['COOL_RATE'], rtol=1.e-10, atol=0.)


def test_calc_evap_sign_convention_unchanged():
    """Legacy convention: QREVP < 0 and COOL_RATE < 0 when subsaturated (evaporation)."""
    ref = np.load(REFERENCE_FILE)
    QREVP, COOL_RATE = dsd.calc_evap(ref['rho'], ref['T'], ref['p'], ref['RH'], ref['N0'],
                                     ref['lamda'], ref['mu'])
    subsat = ref['RH'] < 95.
    assert np.all(QREVP[subsat] < 0.)
    assert np.all(COOL_RATE[subsat] < 0.)
